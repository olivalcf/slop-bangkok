import { readFileSync, writeFileSync } from 'node:fs';

// Refresh with the checked-in Overpass query. Geometry is projected to metres,
// east = +x, north = -z, origin at the Sala Daeng intersection.
const raw = JSON.parse(readFileSync(new URL('./data/osm_bangkok.json', import.meta.url)));
if (raw.remark || !raw.elements?.length) throw new Error(raw.remark || 'Empty OSM response');
const project = ({ lat, lon }) => [
  Math.round((lon - 100.534) * 111320 * Math.cos(13.73 * Math.PI / 180) * 10) / 10,
  Math.round((13.7285 - lat) * 111320 * 10) / 10
];
const roads = [], buildings = [], water = [], parks = [], rail = [];
for (const e of raw.elements) {
  if (!e.geometry?.length) continue;
  const t = e.tags || {}, points = e.geometry.map(project);
  if (t.highway) {
    const lanes = Number.parseInt(t.lanes) || ({ primary: 4, secondary: 4, tertiary: 2, trunk: 6 }[t.highway] || 2);
    roads.push({ id: e.id, name: t['name:en'] || t.name || 'Soi', points,
      width: Number.parseFloat(t.width) || Math.max(6, lanes * 3.2),
      major: ['primary', 'secondary', 'trunk'].includes(t.highway), bridge: t.bridge === 'yes',
      oneway: t.oneway === 'yes' ? 1 : t.oneway === '-1' ? -1 : 0 });
  } else if (t.building) {
    buildings.push({ points, height: Number.parseFloat(t.height) || (Number.parseFloat(t['building:levels']) || 0) * 3.2,
      name: t['name:en'] || t.name || '', kind: t.building });
  } else if (t.natural === 'water') water.push(points);
  else if (t.waterway === 'river') water.push({ line: points });
  else if (t.leisure === 'park') parks.push({ name: t['name:en'] || t.name || 'Park', points });
  else if (t.railway) rail.push(points);
}
const data = { attribution: '© OpenStreetMap contributors, ODbL',
  fetched: raw.osm3s?.timestamp_osm_base, origin: [13.7285, 100.534], roads, buildings, water, parks, rail };
writeFileSync(new URL('../js/bangkok-geodata.js', import.meta.url), `// Generated by tools/build-bangkok.mjs. OSM data, ODbL.\nexport const BKK = ${JSON.stringify(data)};\n`);
console.log({ roads: roads.length, buildings: buildings.length, water: water.length, parks: parks.length, rail: rail.length });
